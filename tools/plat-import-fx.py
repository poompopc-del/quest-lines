#!/usr/bin/env python3
"""Import CC0 effect sprites into Platform Mode — run from the repo root:

    python3 tools/plat-import-fx.py <fx dir>

<fx dir> holds:
    pvfx/effects/<id>/grid/{sprite-sheet.png,manifest.json}   PVFX Foundry by nerijs (CC0) — 96 x 96 frames, 5 per row, 20 fps
    fire1_64.png                                              "Animated Fire" by BenHickling (CC0) — 64 x 64, 10 x 6 frames

Writes public/fx/<key>.png (one row per effect, frames cropped to their union box, centred) and
public/js/plat/fx-sheets.js (PLAT.FX_SHEETS: { key: { img, fw, fh, n, rate, scale, pixel } } — merged into PLAT.FXDEF).
Re-running gives byte-identical output.
"""
import json, os, sys
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else '.'
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'public')
# game key: (pvfx effect id, scale, every nth frame)
PVFX = {
    'wexp':    ('warm-explosion', 1.0, 1),    # bombs, cannonballs, burning / DUO explosions
    'zap':     ('electric-impact', .9, 1),    # chain lightning, storm parry
    'aparry':  ('arcane-parry', .8, 1),       # every successful parry
    'fnova':   ('frost-nova', 1.1, 1),        # parry wave boon, frost orb
    'shrap':   ('solar-shrapnel', 1.2, 1),    # counter wave (talent), perfect hits
    'ldust':   ('landing-dust', 1.2, 1),      # boss landings / slams
    'smoke':   ('smoke-puff', 1.0, 1),        # cannon smoke, vent puffs
    'heal':    ('radiant-heal', .9, 1),       # potions, lifesteal, villager rescue
    'fcharge': ('focus-charge', .8, 1),       # a charge level reached, ULT ready
    'void':    ('void-implosion', 1.1, 1),    # warlock warps / summons
    'splash':  ('splash-crown', 1.0, 1),      # aqua spirit warps, water
    'acid':    ('acid-splash', 1.0, 1),       # poison vents erupting
    'rupture': ('earth-rupture', 1.2, 1),     # ground pounds (gargantuar, dragon stomp, snail)
}
def union(frames):
    x0 = y0 = 10 ** 9; x1 = y1 = -1
    for f in frames:
        b = f.getbbox()
        if b: x0, y0, x1, y1 = min(x0, b[0]), min(y0, b[1]), max(x1, b[2]), max(y1, b[3])
    return x0, y0, x1, y1
def strip(key, frames, center, out):
    # crop symmetric around the frame centre so the effect stays centred on the anchor
    x0, y0, x1, y1 = union(frames); cx, cy = center
    hw = max(cx - x0, x1 - cx); hh = max(cy - y0, y1 - cy)
    box = (cx - hw, cy - hh, cx + hw, cy + hh); w, h = box[2] - box[0], box[3] - box[1]
    s = Image.new('RGBA', (w * len(frames), h), (0, 0, 0, 0))
    for i, f in enumerate(frames): s.paste(f.crop(box), (i * w, 0))
    os.makedirs(os.path.dirname(out), exist_ok=True); s.save(out, optimize=True)
    return w, h, y1 - cy                                   # foot: how far the effect's lowest pixel sits below the centre
sheets = {}
for key, (eid, scale, step) in PVFX.items():
    d = os.path.join(SRC, 'pvfx', 'effects', eid, 'grid')
    m = json.load(open(os.path.join(d, 'manifest.json'))); im = Image.open(os.path.join(d, 'sprite-sheet.png')).convert('RGBA')
    n = len(m['frames']); fw, fh = m['source_size']
    frames = [im.crop(((i % 5) * fw, (i // 5) * fh, (i % 5) * fw + fw, (i // 5) * fh + fh)) for i in range(0, n, step)]
    w, h, foot = strip(key, frames, (fw // 2, fh // 2), os.path.join(ROOT, 'fx', key + '.png'))
    sheets[key] = {'img': f'fx/{key}.png', 'fw': w, 'fh': h, 'n': len(frames), 'rate': 3 * step, 'scale': scale, 'pixel': True, 'foot': foot}
    print(f'{key:8s} {eid:18s} {len(frames):2d} frames {w}x{h}')
# fire: 60 frames on a 10 x 6 grid → every 2nd frame (30), anchored at the frame centre
im = Image.open(os.path.join(SRC, 'fire1_64.png')).convert('RGBA')
frames = [im.crop(((i % 10) * 64, (i // 10) * 64, (i % 10) * 64 + 64, (i // 10) * 64 + 64)) for i in range(0, 60, 2)]
w, h, foot = strip('fire', frames, (32, 32), os.path.join(ROOT, 'fx', 'fire.png'))
sheets['fire'] = {'img': 'fx/fire.png', 'fw': w, 'fh': h, 'n': len(frames), 'rate': 3, 'scale': .6, 'pixel': True, 'foot': foot}
print(f'fire     animated-fire      {len(frames)} frames {w}x{h}')
with open(os.path.join(ROOT, 'js', 'plat', 'fx-sheets.js'), 'w') as f:
    f.write('/* GENERATED by tools/plat-import-fx.py — do not edit by hand.\n'
            '   CC0 effects: PVFX Foundry by nerijs · Animated Fire by BenHickling (see fx/CREDITS.txt). Frames are centred. */\n')
    f.write("(function (G) { 'use strict';\nG.PLAT = G.PLAT || {};\n")
    f.write('G.PLAT.FX_SHEETS = ' + json.dumps(sheets, separators=(',', ':')) + ';\n')
    f.write("})(typeof window !== 'undefined' ? window : globalThis);\n")
print('wrote js/plat/fx-sheets.js')
